export type StringKey = keyof typeof EN;

const TABLES: Record<string, Partial<Record<StringKey, string>>> = { en: EN };
let lang = 'en';

export function setLanguage(l: string): void { lang = TABLES[l] ? l : 'en'; }

export function t(key: StringKey, ...args: (string | number)[]): string {
  let s = TABLES[lang]?.[key] ?? EN[key] ?? key;
  args.forEach((a, i) => { s = s.replace(`{${i}}`, String(a)); });
  return s;
}
