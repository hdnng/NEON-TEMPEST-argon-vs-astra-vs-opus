export function getPose(name: string): Pose {
  return POSES[name] ?? POSES.stance;
}

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const lerpV = (a: V2, b: V2, t: number, out: V2): V2 => { out[0] = lerp(a[0], b[0], t); out[1] = lerp(a[1], b[1], t); return out; };

/** Interpolates two poses into `out` (allocation-free when out is reused). */
export function blendPose(a: Pose, b: Pose, t: number, out: Pose): Pose {
  lerpV(a.hip, b.hip, t, out.hip);
  out.lean = lerp(a.lean, b.lean, t);
  out.head = lerp(a.head, b.head, t);
  lerpV(a.fh, b.fh, t, out.fh);
  lerpV(a.bh, b.bh, t, out.bh);
  lerpV(a.ff, b.ff, t, out.ff);
  lerpV(a.bf, b.bf, t, out.bf);
  out.rot = lerp(a.rot ?? 0, b.rot ?? 0, t);
  out.open = t < 0.5 ? a.open : b.open;
  return out;
}

export function newPose(): Pose {
  return { hip: [0, 0], lean: 0, head: 0, fh: [0, 0], bh: [0, 0], ff: [0, 0], bf: [0, 0], rot: 0, open: false };
}

export function copyPose(src: Pose, out: Pose): Pose {
  return blendPose(src, src, 0, out);
}
