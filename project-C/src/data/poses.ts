/**
 * Pose library. Poses are IK targets for an articulated skeleton, authored for the reference
 * body (HAYATE, ~246px tall) facing right with +y up and the origin between the feet:
 *   hip        pelvis position
 *   lean       torso angle from vertical in degrees (+ leans toward the opponent)
 *   head       extra head tilt in degrees (+ looks down/forward)
 *   fh / bh    near / far hand targets
 *   ff / bf    near / far foot targets
 *   rot        optional whole-body rotation around the hips (flips, tumbles)
 *   open       open hands (palms) instead of fists
 * Characters scale these by their body scale; two-bone IK solves elbows and knees.
 */

export type V2 = [number, number];

export interface Pose {
  hip: V2;
  lean: number;
  head: number;
  fh: V2;
  bh: V2;
  ff: V2;
  bf: V2;
  rot?: number;
  open?: boolean;
}

